#!/usr/bin/env python3
"""Generate j2me/src/hl4/game/Tab.java: the game's constant tables (.rodata/.data arrays of the original) as Java arrays.
Each entry: (symbol, JavaName, width in bytes, signed).  Values come straight from binary.mod (little endian); re-run after editing SPEC."""
import os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from andelf import AndElf
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
B = os.path.join(ROOT, 'work', 'orig', 'android', '영웅서기4.apk!', 'res', 'raw', 'jarfile.mp3!', 'binary.mod')
SPEC = [
    ('ITEM_SELL_CNT', 'ITEM_SELL_CNT', 1, True),
    ('weapon.19612', 'START_WEAPON', 1, True),
    ('SCREEN_COLOR', 'SCREEN_COLOR', 4, True),
    ('TURN_R45', 'TURN_R45', 1, True),
    ('TURN_L45', 'TURN_L45', 1, True),
    ('TURN_R90', 'TURN_R90', 1, True),
    ('TURN_L90', 'TURN_L90', 1, True),
    ('TURN_180', 'TURN_180', 1, True),
    ('VEC_X', 'VEC_X', 1, True),
    ('VEC_Y', 'VEC_Y', 1, True),
    ('C.14.18224', 'BLEND_PARAMS', 2, True),
    ('C.5.16487', 'EFF_GOOD', 1, True),
    ('C.6.16502', 'EFF_BAD', 1, True),
    ('C.7.16515', 'EFF_MAGIC', 1, True),
    ('C.47.16090', 'PS_COUNT', 1, True),
    ('C.48.16091', 'PS_FILE', 1, True),
    ('C.39.18590', 'HP_COUNT', 1, True),
    ('C.40.18591', 'HP_FILE', 1, True),
    ('C.3.16224', 'FOLDER_IMG', 1, True),
    ('C.4.16225', 'FOLDER_IMG2', 1, True),
    ('C.20.18376', 'HERO_SKIP_0', 1, True),
    ('C.21.18377', 'HERO_SKIP_1', 1, True),
    ('C.22.18378', 'HERO_SKIP_2', 1, True),
    ('C.23.18379', 'HERO_SKIP_3', 1, True),
    ('CAMERA_RANGE', 'CAMERA_RANGE', 1, True),
    ('um_sin', 'UM_SIN', 4, True),
    ('um_cos', 'UM_COS', 4, True),
]
e = AndElf(B)
out = ['package hl4.game;', '', '/** Constant tables of the original (generated by tools/gen_tab.py from binary.mod; do not edit). */', 'public final class Tab {', '    private Tab() {', '    }', '']
for sym, jn, w, sg in SPEC:
    o = [x for x in e.objs if x[2] == sym][0]
    raw = e.data[e.off(o[0]):e.off(o[0]) + o[1]]
    n = len(raw) // w
    fmt = {1: 'b' if sg else 'B', 2: 'h' if sg else 'H', 4: 'i' if sg else 'I'}[w]
    vals = struct.unpack('<%d%s' % (n, fmt), raw)
    jt = {1: 'byte', 2: 'short', 4: 'int'}[w]
    body = ', '.join(('(%s) %d' % (jt, v)) if w < 4 else str(v) for v in vals)
    out.append('    /** %s @%#x */' % (sym, o[0]))
    out.append('    public static final %s[] %s = {%s};' % (jt, jn, body))
    out.append('')
out.append('}')
open(os.path.join(ROOT, 'j2me', 'src', 'hl4', 'game', 'Tab.java'), 'w').write('\n'.join(out) + '\n')
print('ok', len(SPEC))

#!/usr/bin/env python3
"""Extract the EUC-KR literals the game code references from AND2011 .rodata into hl4/game/Strs.java.
Each entry: name -> real vaddr (Ghidra 'DAT_000exxxx' = real 0xdxxxx: Ghidra's image base is 0x10000 higher).
Usage: python3 tools/gen_strs.py <binary.mod> <out java>"""
import sys

ENTRIES = [
    ('LOGO_AUTH_ERR', 0xd88e0, 'LogoFrame_Render state 3'),
    ('LOGO_OK', 0xd88f0, 'LogoFrame_Render state 1 (drawGMenuBackFrame bottom label)'),
    ('LOGO_TITLE', 0xd88f8, 'LogoFrame_Render state 1 ribbon title'),
    ('LOGO_CALL', 0xd8908, 'LogoFrame_Render state 1 select=1 heading'),
    ('TITLE_AGREE', 0xd9948, 'TitleFrame_Render consent button 1'),
    ('TITLE_REFUSE', 0xd9950, 'TitleFrame_Render consent button 2'),
]

ASCII = [('PHONE', '02-559-8787'), ('EA', 'ELECTRONIC ARTS KOREA LLC'), ('VER', '1.0.0'), ('TOUCH_SCREEN', 'TOUCH THE SCREEN')]


def main():
    d = open(sys.argv[1], 'rb').read()
    out = ['package hl4.game;', '', '/** EUC-KR literals of the original (generated by tools/gen_strs.py; NUL padded so the text engine may read one byte past the end). */',
           'public final class Strs {', '    private Strs() {', '    }', '']
    for name, addr, why in ENTRIES:
        i = addr
        while d[i] != 0:
            i += 1
        b = d[addr:i]
        out.append('    /** @0x%x %s */' % (addr, why))
        out.append('    public static final byte[] %s = {%s};' % (name, ', '.join(str(x - 256 if x > 127 else x) for x in list(b) + [0, 0, 0, 0])))
        out.append('')
    for n, v in ASCII:
        out.append('    public static final byte[] %s = ascii("%s");' % (n, v))
    out.append('')
    out.append('    /** dlib_strlen */')
    out.append('    public static int len(byte[] b) {')
    out.append('        int i = 0;')
    out.append('        while (i < b.length && b[i] != 0) {')
    out.append('            i++;')
    out.append('        }')
    out.append('        return i;')
    out.append('    }')
    out.append('')
    out.append('    public static byte[] ascii(String s) {')
    out.append('        byte[] b = new byte[s.length() + 4];')
    out.append('        for (int i = 0; i < s.length(); i++) {')
    out.append('            b[i] = (byte) s.charAt(i);')
    out.append('        }')
    out.append('        return b;')
    out.append('    }')
    out.append('}')
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')


main()
